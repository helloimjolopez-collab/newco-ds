#!/usr/bin/env node
/**
 * build-theme-alias.js
 *
 * Emits src/tokens/theme.css — a mode-agnostic "role alias" layer on top of the
 * color semantics. Today a consumer must pick a mode by name
 * (--semantic-color-light-mode-… vs --semantic-color-midnight-mode-…). This layer
 * exposes short role names that resolve to the right mode automatically via a
 * single `data-theme` attribute on any ancestor:
 *
 *   --fill-action-primary-base  ->  light value by default,
 *                                   midnight value under [data-theme="midnight"]
 *
 * Usage in a consuming app (include AFTER tokens.css):
 *   <link rel="stylesheet" href="…/tokens.css" />
 *   <link rel="stylesheet" href="…/theme.css" />
 *   <html data-theme="midnight"> … </html>   <!-- flip the whole app with one attr -->
 *
 * Color only — type/layout/motion use responsive (Desktop/Mobile) modes, a
 * different axis handled by breakpoints/media, not data-theme.
 *
 * Run AFTER build-token-source.js (needs tokens/newco-design-tokens.json).
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");
const dtcg = JSON.parse(readFileSync(resolve(root, "tokens", "newco-design-tokens.json"), "utf8"));

// Collect dotted leaf paths under a subtree, e.g. ["fill","action","primary","base"].
function leaves(node, trail = [], out = []) {
  for (const [k, v] of Object.entries(node)) {
    if (v && typeof v === "object" && "$value" in v) out.push(trail.concat(k));
    else if (v && typeof v === "object") leaves(v, trail.concat(k), out);
  }
  return out;
}

const light = dtcg["semantic-color"]["light-mode"];
const midnight = dtcg["semantic-color"]["midnight-mode"];
const paths = leaves(light).map((p) => p.join("-")).sort();

// Does midnight define this same path?
const midSet = new Set(leaves(midnight).map((p) => p.join("-")));

const aliasLine = (p, mode) =>
  `  --${p}: var(--semantic-color-${mode}-mode-${p});`;

const rootBlock = paths.map((p) => aliasLine(p, "light")).join("\n");
const lightBlock = paths.map((p) => aliasLine(p, "light")).join("\n");
const midBlock = paths
  .filter((p) => midSet.has(p))
  .map((p) => aliasLine(p, "midnight"))
  .join("\n");

const css = `/* <auto-generated> theme-alias layer — scripts/build-theme-alias.js. Do not edit. */
/*
 * Mode-agnostic role aliases. Include AFTER tokens.css, then set data-theme.
 *   --fill-action-primary-base resolves to light by default, midnight under
 *   [data-theme="midnight"]. Nest [data-theme="light"] to opt a subtree back.
 */
:root {
${rootBlock}
}

[data-theme="light"] {
${lightBlock}
}

[data-theme="midnight"] {
${midBlock}
}
`;

mkdirSync(resolve(root, "src", "tokens"), { recursive: true });
writeFileSync(resolve(root, "src", "tokens", "theme.css"), css, "utf8");
console.log(`theme.css: ${paths.length} role aliases (${midSet.size} with a midnight override).`);
